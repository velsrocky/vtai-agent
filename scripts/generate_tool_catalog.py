#!/usr/bin/env python3
"""Generate docs/tool-catalog.md from the live tool registry.

One generated source of truth for what the MCP server exposes — schemas are
read from the pydantic input models, so the doc can't drift from the code.
REA-style setup: behavior is enforced in guardrails.py; this file only
documents the surface.

Usage:
  uv run python scripts/generate_tool_catalog.py           # (re)write the file
  uv run python scripts/generate_tool_catalog.py --check   # CI: exit 1 on drift
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from vtai_agent.mcp_server import register_tools  # noqa: E402
from vtai_agent.tools.registry import registry  # noqa: E402

HEADER = """<!-- GENERATED by scripts/generate_tool_catalog.py — do not edit by
hand. Re-check with: uv run python scripts/generate_tool_catalog.py --check -->

# MCP tool catalog (generated)

Every tool `vtai_agent.mcp_server.build_server()` exposes on one MCP
connection, {n} tools, name-sorted. Schema text comes straight from the
pydantic input models; naming/error codes live in
`src/vtai_agent/errors.py`; enforcement lives in `guardrails.py`.
"""

TOOL_BODY = """## `{name}`

{description}

| input | type | required | default | description |
|---|---|---|---|---|
{rows}
"""


def _default_repr(info) -> str:
    if info.is_required():
        return "—"
    try:
        default = info.get_default(call_default=False)
    except Exception:
        default = info.default
    text = repr(default)
    if default is None:
        text = "None (config default applies)"
    if len(text) > 40:
        text = text[:37] + "..."
    return text


def _type_name(info) -> str:
    ann = info.annotation
    if isinstance(ann, type):
        return ann.__name__
    return str(ann).replace("typing.", "")


def _clean(desc: str | None) -> str:
    """Pipe breaks the markdown table; escape it."""
    if not desc:
        return ""
    return desc.strip().replace("|", "\\|")


def build_catalog() -> str:
    register_tools()
    tools = dict(sorted(registry.all().items()))
    out = [HEADER.format(n=len(tools))]
    for name, tool in tools.items():
        fields = tool.InputModel.model_fields
        rows = []
        empty_desc = "(no description supplied)"
        for fname, info in fields.items():
            desc = _clean(info.description) or empty_desc
            rows.append("| `%s` | `%s` | %s | %s | %s |" % (
                fname, _type_name(info),
                "yes" if info.is_required() else "no",
                _default_repr(info),
                desc.replace("\n", " "),
            ))
        out.append(TOOL_BODY.format(
            name=name, description=str(tool.description).strip(), rows="\n".join(rows)))
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    target = ROOT / "docs" / "tool-catalog.md"
    content = build_catalog()
    if "--check" in sys.argv:
        committed = target.read_text(encoding="utf-8") if target.exists() else ""
        if committed != content:
            print(
                "catalog drift: docs/tool-catalog.md is stale.\n"
                "Re-run: uv run python scripts/generate_tool_catalog.py",
                file=sys.stderr,
            )
            return 1
        print("catalog check: in sync")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
